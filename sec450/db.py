class Row(tuple):
    """A result row readable by position or by column name, like sqlite3.Row."""

    _index: dict[str, int]

    def __getitem__(self, key: Any) -> Any:  # type: ignore[override]
        if isinstance(key, str):
            return tuple.__getitem__(self, self._index[key])
        return tuple.__getitem__(self, key)

    def keys(self) -> list[str]:
        return list(self._index)


def _row_factory(cursor: psycopg.Cursor[Any]) -> RowMaker[Row]:
    index = {c.name: i for i, c in enumerate(cursor.description or ())}

    def make(values: Sequence[Any]) -> Row:
        row = Row(values)
        row._index = index
        return row
    return make


Connection = psycopg.Connection[Row]


def one(cursor: psycopg.Cursor[Row]) -> Row:
    """The row of a query that always returns one (COUNT, COALESCE(MAX), INSERT ... RETURNING)."""
    row = cursor.fetchone()
    if row is None:
        raise RuntimeError("query returned no row")
    return row

# Advisory lock keys for transaction(). WRITE serializes the collector and analysis
# writers the way SQLite's single writer did; AUDIT serializes only the audit chain,
# so API requests never wait behind a collector batch.
WRITE_LOCK = 450_001
AUDIT_LOCK = 450_002


def conninfo(cfg: DatabaseConfig) -> str:
    return make_conninfo(host=cfg.host, port=cfg.port, dbname=cfg.name, user=cfg.user,
                         password=os.environ.get(cfg.password_env) or None,
                         connect_timeout=cfg.connect_timeout_seconds, application_name="sec450")


def connect(cfg: DatabaseConfig) -> Connection:
    """Open a connection in autocommit mode; use transaction() for writes."""
    return psycopg.connect(conninfo(cfg), autocommit=True, row_factory=_row_factory)


class Pool:
    """Reuses connections for the API: opening one costs ~10 ms, three times per request.

    No background threads: connections open on demand, and an idle one is checked with an
    empty query before reuse, so a PostgreSQL restart costs a reconnect, not failed requests.
    """

    def __init__(self, cfg: DatabaseConfig, max_idle: int = 8):
        self.cfg = cfg
        self._idle: queue.LifoQueue[Connection] = queue.LifoQueue(max_idle)

    def _get(self) -> Connection:
        while True:
            try:
                conn = self._idle.get_nowait()
            except queue.Empty:
                return connect(self.cfg)
            try:
                conn.execute("")
                return conn
            except psycopg.Error:
                conn.close()

    @contextmanager
    def connection(self) -> Iterator[Connection]:
        conn = self._get()
        try:
            yield conn
        finally:
            if conn.closed or in_transaction(conn):
                conn.close()
            else:
                try:
                    self._idle.put_nowait(conn)
                except queue.Full:
                    conn.close()


def init_db(conn: Connection) -> None:
    collation = one(conn.execute("SELECT datcollate FROM pg_database WHERE datname = current_database()"))[0]
    if collation != "C":
        raise RuntimeError(f"database collation is {collation!r}; it must be 'C' so timestamp text sorts "
                           "in time order (create it with --locale=C, see docker-compose.yml)")
    with transaction(conn):   # the lock keeps collector and api from creating tables at the same time
        conn.execute(SCHEMA)


def copy_rows(conn: Connection, table: str, columns: Sequence[str], rows: Iterable[Sequence[Any]]) -> None:
    """Bulk-load rows with COPY (seeding and the SQLite migration); table and columns are fixed names."""
    with conn.cursor().copy(f"COPY {table} ({', '.join(columns)}) FROM STDIN") as copy:
        for row in rows:
            copy.write_row(row)


def in_transaction(conn: Connection) -> bool:
    return conn.info.transaction_status != TransactionStatus.IDLE


@contextmanager
def transaction(conn: Connection, lock: int = WRITE_LOCK) -> Iterator[Connection]:
    """BEGIN ... COMMIT under an advisory lock, rolling back on any exception.

    The lock gives each writer the whole database (or the audit chain) to itself
    until COMMIT, like SQLite's BEGIN IMMEDIATE: reading the last chain hash and
    appending the next row can never interleave with another writer (DD-07, DD-08).
    """
    conn.execute("BEGIN")
    try:
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (lock,))
        yield conn
        conn.execute("COMMIT")
    except BaseException:
        if not conn.closed and in_transaction(conn):
            conn.execute("ROLLBACK")
        raise
